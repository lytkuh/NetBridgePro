using System.Windows;

namespace NetBridge.Windows.Core;

/// <summary>Bilingual UI strings (fa default / en). Applied at startup; restart to switch.</summary>
public static class I18N
{
    public static string CurrentLang { get; private set; } = "fa";

    public static FlowDirection Dir => CurrentLang == "fa" ? FlowDirection.RightToLeft : FlowDirection.LeftToRight;

    private static Dictionary<string, string> _map;

    // Static ctors run AFTER every field initializer, so Fa/En are ready here.
    // (Assigning "_map = Fa" directly as a field initializer ran BEFORE Fa was
    // built and crashed startup with TypeInitializationException.)
    static I18N() => _map = Fa;

    public static void Init(string lang)
    {
        CurrentLang = lang == "en" ? "en" : "fa";
        _map = CurrentLang == "en" ? En : Fa;
    }

    public static string T(string key) => _map.TryGetValue(key, out var v) ? v : key;

